"""Sensor data in a result bundle: the redistributable-dataset allow list.

A bundle always carries the scores, the boxes, the poses and the repro card.
LiDAR points and camera images are only carried when **every** one of these is
true:

1. the exporter names the dataset explicitly (``dataset_id``; it is never
   inferred from a file or folder name),
2. the dataset is on the explicit allow list below, whose licence comes from
   the dataset catalog's recorded ``licence`` field (or, for Coperceive's own
   synthetic scenes, from this file),
3. the exporter ticks "Include sensor data (licence: …)", and
4. the selected frames' sensor bytes fit the sensor-data cap.

Anything else is omitted and the bundle records why. OPV2V, V2XSet, V2V4Real,
DAIR-V2X-C, generic datasets and unknown datasets are never on the allow list.
"""

from __future__ import annotations

from dataclasses import dataclass

# The default sensor-data cap: uncompressed LiDAR + camera bytes for the
# included frames. Both export and open use it; Python callers override it with
# ``BundleExportRequest.sensor_max_bytes`` and ``OpenLimits.max_sensor_bytes``.
SENSOR_MAX_BYTES = 50 * 1024 * 1024

# Coperceive-generated scenes. Their bytes are generated by Apache-2.0 code in
# this repository; no third-party dataset is involved, so they may be shared.
SYNTHETIC_DATASETS: dict[str, tuple[str, str]] = {
    # dataset key -> (recorded licence, people-facing label)
    "demo": ("Apache-2.0", "Coperceive demo (synthetic)"),
    "fixture": ("Apache-2.0", "synthetic fixture"),
    "synthetic": ("Apache-2.0", "synthetic scene"),
    "generated": ("Apache-2.0", "generated scene"),
}

# Datasets whose licence the catalog records as fully redistributable. The
# licence is read from the catalog at lookup time; the allow list is refused if
# the catalog stops recording exactly this licence.
CATALOG_ALLOWED: dict[str, tuple[str, str]] = {
    # dataset key -> (dataset id in the catalog, required licence key)
    "griffin": ("griffin", "mit"),
}

# Named refusals, so the reason is specific in the export review. Every other
# dataset id is refused as unknown by the default-deny rule below.
REFUSED_DATASETS: dict[str, str] = {
    "opv2v": "OPV2V",
    "v2xset": "V2XSet",
    "v2v4real": "V2V4Real",
    "dairv2xc": "DAIR-V2X-C",
    "generic": "generic datasets",
}

# The adapter that ingests each dataset. A local copy matches a bundle only when
# its ``COMPLETE.json`` records the same adapter (plus the scene id and frame
# count); this is how the recipient's library proves it is the same dataset.
DATASET_ADAPTERS: dict[str, str] = {
    "demo": "generic",
    "fixture": "generic",
    "synthetic": "generic",
    "generated": "generic",
    "griffin": "griffin",
    "opv2v": "opv2v",
    "v2xset": "v2xset",
    "v2v4real": "v2v4real",
    "dairv2xc": "dair-v2x-c",
}


def dataset_key(value: str) -> str:
    """Lowercase letters and digits only, so ``V2X-Set`` matches ``v2xset``."""
    return "".join(character for character in value.strip().lower() if character.isalnum())


@dataclass(frozen=True)
class SensorPolicy:
    """Whether one dataset's sensor bytes may travel in a bundle."""

    dataset_id: str | None
    allowed: bool
    licence: str | None = None
    licence_url: str | None = None
    dataset_label: str | None = None
    adapter: str | None = None
    reason: str = ""

    def as_document(self) -> dict[str, object]:
        return {
            "dataset_id": self.dataset_id,
            "allowed": self.allowed,
            "licence": self.licence,
            "licence_url": self.licence_url,
            "dataset_label": self.dataset_label,
            "adapter": self.adapter,
            "reason": self.reason,
        }


def _refused(dataset_id: str, reason: str) -> SensorPolicy:
    key = dataset_key(dataset_id)
    return SensorPolicy(
        dataset_id=dataset_id,
        allowed=False,
        adapter=DATASET_ADAPTERS.get(key),
        reason=reason,
    )


def _catalog_dataset_row(dataset_id: str) -> dict[str, object] | None:
    from coperceive.catalog import get_dataset

    try:
        row = get_dataset(dataset_id)
    except (OSError, ValueError):
        return None
    return row


def sensor_data_policy(dataset_id: str | None) -> SensorPolicy:
    """The explicit allow-list decision for one dataset id.

    Never infers a dataset from a name: a missing id is a refusal, and the
    mapping from id to licence is this module's, not a guess from a scene id.
    """
    if dataset_id is None or not dataset_id.strip():
        return SensorPolicy(
            dataset_id=None,
            allowed=False,
            reason="the exporter did not name a dataset, so its licence is unknown",
        )
    key = dataset_key(dataset_id)
    if not key:
        return _refused(dataset_id, f"the dataset id {dataset_id!r} has no letters or digits")
    if key in SYNTHETIC_DATASETS:
        licence, label = SYNTHETIC_DATASETS[key]
        return SensorPolicy(
            dataset_id=dataset_id.strip(),
            allowed=True,
            licence=licence,
            dataset_label=label,
            adapter=DATASET_ADAPTERS.get(key, "generic"),
        )
    if key in CATALOG_ALLOWED:
        catalog_id, required = CATALOG_ALLOWED[key]
        row = _catalog_dataset_row(catalog_id)
        if row is None:
            return _refused(
                dataset_id,
                f"the dataset catalog does not record {catalog_id!r}, so the licence is unknown",
            )
        recorded = dataset_key(str(row.get("licence") or ""))
        if recorded != required:
            return _refused(
                dataset_id,
                f"the dataset catalog records licence {row.get('licence')!r}; "
                "only a recorded MIT licence allows redistribution",
            )
        label = row.get("name")
        url = row.get("licence_url")
        return SensorPolicy(
            dataset_id=dataset_id.strip(),
            allowed=True,
            licence=str(row.get("licence")),
            licence_url=url if isinstance(url, str) else None,
            dataset_label=label if isinstance(label, str) and label else catalog_id,
            adapter=DATASET_ADAPTERS.get(key, key),
        )
    if key in REFUSED_DATASETS:
        name = REFUSED_DATASETS[key]
        return _refused(
            dataset_id,
            f"sensor data for {name} is never redistributed (no redistributable licence is recorded)",
        )
    return _refused(
        dataset_id,
        f"no redistributable licence is recorded for dataset {dataset_id!r}; "
        "only demo, synthetic/generated scenes and Griffin are on the allow list",
    )


def allow_list_document() -> dict[str, object]:
    """The mapping a reviewer can read, and the export review shows for a dataset."""
    return {
        "synthetic": {
            key: {"licence": licence, "label": label}
            for key, (licence, label) in sorted(SYNTHETIC_DATASETS.items())
        },
        "catalog": {
            key: {"catalog_id": catalog_id, "licence": required}
            for key, (catalog_id, required) in sorted(CATALOG_ALLOWED.items())
        },
        "refused": dict(sorted(REFUSED_DATASETS.items())),
    }
