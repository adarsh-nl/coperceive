"""Test helpers for the OpenCOOD plugin: load its modules, build fake checkpoints, copy it.

The plugin's worker is a script (``{python} {plugin_dir}/worker.py``) that imports its sibling
modules by name, as Griffin's does; loading the modules here therefore puts the package
directory on ``sys.path`` and returns them as ``Any`` so pyright's strict mode stays happy
about a directory outside ``pyright include``.
"""

from __future__ import annotations

import importlib
import io
import json
import shutil
import sys
import zipfile
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
PLUGIN_DIR = ROOT / "plugins" / "opencood" / "coperceive_opencood_model"
MANIFEST = PLUGIN_DIR / "model.yaml"
FAKE_OPENCOOD_PARENT = Path(__file__).resolve().parent / "fake_opencood"

_LOADED: dict[str, Any] = {}

# The plugin's modules carry an ``opencood_`` prefix so that a top-level ``import convert``
# in this test process can never resolve to the plugin's module instead of another plugin's
# (plugins/griffin/tests/test_convert.py imports its sibling ``convert`` by name). The short
# names are what the tests call these modules.
_MODULES = {
    "batch": "opencood_batch",
    "checkpoint": "opencood_checkpoint",
    "convert": "opencood_convert",
    "engine": "opencood_engine",
}


def load(name: str) -> Any:
    """Import one of the plugin package's modules (``convert``, ``batch``, …) by file."""
    if name not in _LOADED:
        directory = str(PLUGIN_DIR)
        if directory not in sys.path:
            sys.path.insert(0, directory)
        _LOADED[name] = importlib.import_module(_MODULES.get(name, name))
    return _LOADED[name]


def fake_config() -> dict[str, Any]:
    """A tiny OpenCOOD config with the keys the engine reads (fusion, order, max_cav)."""
    return {
        "name": "fake-cobevt",
        "fusion": {"core_method": "IntermediateFusionDataset", "args": []},
        "preprocess": {
            "core_method": "SpVoxelPreprocessor",
            "args": {"voxel_size": [0.4, 0.4, 4.0], "max_points_per_voxel": 32},
            "cav_lidar_range": [-70.4, -40.0, -3.0, 70.4, 40.0, 1.0],
        },
        "postprocess": {
            "core_method": "VoxelPostprocessor",
            "order": "hwl",
            "max_num": 100,
            "target_args": {"score_threshold": 0.2},
        },
        "train_params": {"max_cav": 5},
        "data_augment": [],
    }


def config_bytes(config: dict[str, Any] | None = None) -> bytes:
    return yaml.safe_dump(config or fake_config(), sort_keys=True).encode("utf-8")


def write_checkpoint(
    path: Path, *, config: dict[str, Any] | None = None, weights: bytes | None = None
) -> Path:
    """A checkpoint archive shaped the way the worker discovers one: config + weights."""
    if weights is None:
        weights = b"not a torch checkpoint; discovery tests never load it"
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as bundle:
        bundle.writestr("cobevt-lidar/config.yaml", config_bytes(config))
        bundle.writestr("cobevt-lidar/net_epoch_bestval_at_10.pth", weights)
    path.write_bytes(buffer.getvalue())
    return path


def torch_weights_bytes() -> bytes:
    """A minimal real ``torch.save`` payload, so ``torch.load`` in the engine succeeds."""
    import torch  # noqa: PLC0415 - only the chain tests need it

    buffer = io.BytesIO()
    torch.save({"model": {"fake.weight": torch.zeros(1)}}, buffer)
    return buffer.getvalue()


def copy_plugin_for_tests(directory: Path) -> Path:
    """A copy of the package whose manifest runs in ``coperceive``'s interpreter with the fake.

    Returns the manifest path of the copy (``<directory>/model.yaml``); ``{plugin_dir}`` is
    ``<directory>``, which holds the worker and its sibling modules. A tiny ``run_worker.py``
    puts ``tests/fake_opencood`` on ``sys.path`` first, then calls the real worker's ``main``,
    so the real ``model run`` → worker → engine chain is exercised.
    """
    target = directory / "opencood-plugin"
    shutil.copytree(PLUGIN_DIR, target)
    payload = yaml.safe_load((target / "model.yaml").read_text(encoding="utf-8"))
    payload["environment"] = {"current": True}
    payload["commands"]["batch"] = [
        "{python}",
        "{plugin_dir}/run_worker.py",
        "--model",
        "{model}",
        "--checkpoint",
        "{option:checkpoint}",
    ]
    (target / "model.yaml").write_text(yaml.safe_dump(payload, sort_keys=False), encoding="utf-8")
    (target / "run_worker.py").write_text(
        "# generated by tests/opencood_plugin.py: fake OpenCOOD on sys.path, then the real worker\n"
        "import sys\n"
        f"sys.path.insert(0, {json.dumps(str(FAKE_OPENCOOD_PARENT))})\n"
        "import worker\n"
        "sys.exit(worker.main())\n",
        encoding="utf-8",
    )
    return target / "model.yaml"


def fake_opencood_available() -> bool:
    return (FAKE_OPENCOOD_PARENT / "opencood" / "__init__.py").is_file()
