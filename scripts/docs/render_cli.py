"""Write ``docs/reference/cli.md`` from the real argparse help.

The page is generated. Do not edit it by hand. ``COLUMNS`` is fixed, and the
help text is reflowed so Python 3.11, 3.12, and 3.13 print the same page.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import textwrap
from pathlib import Path
from typing import cast

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "reference" / "cli.md"
os.environ["COLUMNS"] = "100"
sys.path.insert(0, str(ROOT))


def _subparsers(parser: argparse.ArgumentParser) -> list[tuple[str, argparse.ArgumentParser]]:
    found: list[tuple[str, argparse.ArgumentParser]] = []
    actions = cast(list[argparse.Action], getattr(parser, "_actions", []))
    for action in actions:
        raw_choices = getattr(action, "choices", None)
        if not isinstance(raw_choices, dict) or not raw_choices:
            continue
        choices = cast(dict[object, object], raw_choices)
        if not all(isinstance(child, argparse.ArgumentParser) for child in choices.values()):
            continue
        for name, child in choices.items():
            if isinstance(name, str) and isinstance(child, argparse.ArgumentParser):
                found.append((name, child))
    return found


def _stabilize(help_text: str) -> str:
    """Make argparse's help identical on Python 3.11 through 3.13.

    3.13 repeats a short option's metavar (``-o OUT, --out OUT``) and breaks
    usage lines in different places. The words are the same.
    """
    short_metavar = (
        r"(?m)^(?P<indent>\s*)(?P<short>-[A-Za-z]) "
        r"(?P<meta>\S+), (?P<long>--[\w-]+) (?P=meta)(?=\s|$)"
    )
    text = re.sub(
        short_metavar,
        r"\g<indent>\g<short>, \g<long> \g<meta>",
        help_text,
    )
    lines = text.splitlines()
    reflowed: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if line.startswith("usage:"):
            parts = [line.strip()]
            index += 1
            while index < len(lines) and lines[index].startswith("   ") and lines[index].strip():
                parts.append(lines[index].strip())
                index += 1
            joined = " ".join(parts)
            reflowed.extend(
                textwrap.wrap(
                    joined,
                    width=100,
                    subsequent_indent="       ",
                    break_long_words=False,
                    break_on_hyphens=False,
                )
            )
            continue
        reflowed.append(line)
        index += 1
    collapsed: list[str] = []
    option = re.compile(r"^(?P<indent> +)(?P<spec>-\S.*?)\s{2,}(?P<help>\S.*)$")
    for line in reflowed:
        match = option.match(line)
        if match is None:
            collapsed.append(line)
            continue
        collapsed.append(f"{match.group('indent')}{match.group('spec')}  {match.group('help')}")
    return "\n".join(collapsed).rstrip() + "\n"


def _walk(parser: argparse.ArgumentParser, prefix: list[str]) -> list[tuple[list[str], str]]:
    blocks: list[tuple[list[str], str]] = [(prefix, _stabilize(parser.format_help()))]
    for name, child in _subparsers(parser):
        blocks.extend(_walk(child, [*prefix, name]))
    return blocks


def render() -> str:
    from coperceive.cli import build_parser

    lines = [
        "# CLI reference",
        "",
        "Generated by `scripts/docs/render_cli.py` from `ArgumentParser.format_help()`",
        "on the commands registered in `coperceive/cli.py`. Do not edit this file by hand.",
        "Regenerate it with `python scripts/docs/render_cli.py`.",
        "",
        "There is no `coperceive import` command. A raw dataset is read with",
        "`coperceive adapters ingest`. Model boxes are read with",
        "`coperceive predictions import`.",
        "",
    ]
    for prefix, help_text in _walk(build_parser(), ["coperceive"]):
        title = " ".join(prefix)
        lines.append(f"## `{title}`")
        lines.append("")
        lines.append("```text")
        lines.append(help_text.rstrip())
        lines.append("```")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    main()
